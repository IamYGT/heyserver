// Regenerate: go generate ./internal/api/...  or  make gen-routes

// RouteAuth describes the authentication expectation for a registered route.
type RouteAuth string

const (
	RoutePublic       RouteAuth = "public"        // no JWT required
	RouteProtected    RouteAuth = "protected"     // JWT required (any role)
	RouteManager      RouteAuth = "manager"       // JWT + manager or admin role
	RouteAdmin        RouteAuth = "admin"         // JWT + admin role
	RouteAgent        RouteAuth = "agent"         // managed-node identity + agent bearer token
	RouteInternalCron RouteAuth = "internal_cron" // localhost + X-Cron-Secret
)

